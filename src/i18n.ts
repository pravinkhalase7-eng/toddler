export function ui(key: string) {
  return uiPack[getLang()][key] ?? uiPack.en[key] ?? key;
}

export function labelWord(word: string) {
  const lang = getLang();
  if (lang === "en") return word;
  const gloss = words[word] ?? topics[word];
  if (!gloss) return word;
  return lang === "hi" ? gloss[0] : gloss[1];
}

export function topicName(title: string) {
  return labelWord(title);
}

export type Spoken = { text: string; devanagari: boolean };

export function speechFor(text: string, hint?: string): Spoken {
  const lang = getLang();
  if (lang === "en") return { text, devanagari: false };
  const phrase = phrases[lang][text];
  if (phrase) return { text: phrase, devanagari: true };
  const hinted = hint ? words[hint] ?? topics[hint] : undefined;
  if (hinted) return { text: lang === "hi" ? hinted[0] : hinted[1], devanagari: true };
  const direct = words[text] ?? topics[text];
  if (direct) return { text: lang === "hi" ? direct[0] : direct[1], devanagari: true };
  return { text, devanagari: false };
}
